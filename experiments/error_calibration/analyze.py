"""Calibration analysis of the discretization-error truthfulness sweep.

Reads results.json (from sweep.py), computes the truthfulness table, fits the
three candidate calibration models on the log-ratio with leave-one-system-out
cross-validation, quantifies the (ecut, k) cross term on Al, and writes README.md
with every number. Cheap: no SCF, run anywhere.

  uv run python experiments/error_calibration/analyze.py
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
RES = HERE / "results.json"
README = HERE / "README.md"


def load_points(data):
    """Flatten to per-point records. Ratio = est/true (both <= 0 -> positive).

    Descriptors: gap (converged gap_ref, metals -> 0.0), frac = ecut_loose/ecut_ref.
    """
    pts = []
    for name, s in data["systems"].items():
        gap = s["gap_ref_eV"]
        gap = 0.0 if gap is None else float(gap)
        for p in s["points"]:
            est, true = p["est_denergy_eV"], p["true_denergy_eV"]
            pts.append(dict(system=name, metal=s["metal"], gap=gap,
                            frac=p["factor"], est=est, true=true,
                            ratio=p["ratio"],
                            logr=math.log(true / est) if (est < 0 and true < 0) else float("nan")))
    return pts


def geomean_ratio(pts):
    r = np.array([p["ratio"] for p in pts])
    return float(np.exp(np.mean(np.log(r))))


def loso_global(pts):
    """Leave-one-system-out global scale. Correction is a single constant on
    log(true/est); calibrated est = est * exp(const). Report held-out residual."""
    systems = sorted({p["system"] for p in pts})
    resid = []
    for held in systems:
        train = [p for p in pts if p["system"] != held]
        test = [p for p in pts if p["system"] == held]
        c = float(np.mean([p["logr"] for p in train]))     # log-scale constant
        for p in test:
            resid.append(p["logr"] - c)                    # residual after calib
    return np.array(resid)


def loso_linear(pts, descriptors):
    """Leave-one-system-out linear model: logr ~ b0 + sum b_k * descriptor_k."""
    systems = sorted({p["system"] for p in pts})
    resid = []
    coefs = []
    for held in systems:
        train = [p for p in pts if p["system"] != held]
        test = [p for p in pts if p["system"] == held]
        X = np.array([[1.0] + [p[d] for d in descriptors] for p in train])
        y = np.array([p["logr"] for p in train])
        beta, *_ = np.linalg.lstsq(X, y, rcond=None)
        coefs.append(beta)
        for p in test:
            x = np.array([1.0] + [p[d] for d in descriptors])
            resid.append(p["logr"] - float(x @ beta))
    return np.array(resid), np.array(coefs)


def rms(a):
    a = np.asarray(a, dtype=float)
    return float(np.sqrt(np.mean(a ** 2)))


def fit_insample_linear(pts, descriptors):
    X = np.array([[1.0] + [p[d] for d in descriptors] for p in pts])
    y = np.array([p["logr"] for p in pts])
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    pred = X @ beta
    ss_res = float(np.sum((y - pred) ** 2))
    ss_tot = float(np.sum((y - y.mean()) ** 2))
    r2 = 1.0 - ss_res / ss_tot if ss_tot > 0 else float("nan")
    return beta, r2


def main():
    data = json.loads(RES.read_text())
    pts = load_points(data)

    lines = []
    def w(s=""):
        lines.append(s)

    w("# Discretization-error estimator: calibration probe")
    w()
    w("Feasibility probe. Is gradwave's single-shot plane-wave (Ecut) error "
      "estimate (`postscf/discretization_error.py`) truthful enough across "
      "chemistry that a small model calibrates its bias away, and how large is "
      "the (ecut, k-mesh) cross term the additive error budget ignores? "
      "Research-notes register; see `docs/ideas.md` \"Error estimation: the "
      "rest of the budget\".")
    w()
    w("Method: per system, one converged reference cutoff `ecut_ref`; three "
      "loose cutoffs at 0.50 / 0.65 / 0.80 of it. The FFT density grid is fixed "
      "to the reference grid for every run, so only the plane-wave orbital "
      "sphere changes (what the estimator addresses). `ecut_large = ecut_ref`, "
      "so the estimator annulus and the truth window are the same interval. "
      "Truth = `E_total(ecut_ref) - E_total(ecut_loose)`, same k-mesh, same "
      "grid, PBE, norm-conserving ONCV pseudos. All values eV unless noted. "
      "Generated by `analyze.py` from `results.json`.")
    w()

    # ---- truthfulness table ----
    w("## 1. Truthfulness grid")
    w()
    w("`ratio = estimated / true` (both energy lowerings, so a positive ratio; "
      "1.0 = perfect, <1 under-estimates the remaining error, >1 over-estimates).")
    w()
    w("| system | metal | gap_ref eV | factor | ecut_loose Ry | est meV/atom | "
      "true meV/atom | ratio |")
    w("|---|---|---|---|---|---|---|---|")
    for name, s in data["systems"].items():
        for p in s["points"]:
            g = s["gap_ref_eV"]
            gs = "metal" if g is None else f"{g:.2f}"
            w(f"| {name} | {'Y' if s['metal'] else 'N'} | {gs} | "
              f"{p['factor']:.2f} | {p['ecut_loose_ry']:.1f} | "
              f"{p['est_meV_atom']:.2f} | {p['true_meV_atom']:.2f} | "
              f"{p['ratio']:.3f} |")
    w()
    ratios = np.array([p["ratio"] for p in pts])
    gm = geomean_ratio(pts)
    w(f"Ratio summary over {len(pts)} points: min {ratios.min():.3f}, max "
      f"{ratios.max():.3f}, median {np.median(ratios):.3f}, geometric mean "
      f"{gm:.3f}, spread (max/min) {ratios.max()/ratios.min():.2f}x.")
    w()

    # per-system geomean and per-factor pattern
    w("Per-system geometric-mean ratio (systematicity check):")
    w()
    w("| system | geomean ratio | ratios by factor 0.50/0.65/0.80 |")
    w("|---|---|---|")
    for name, s in data["systems"].items():
        rr = [p["ratio"] for p in s["points"]]
        gmn = float(np.exp(np.mean(np.log(rr))))
        w(f"| {name} | {gmn:.3f} | "
          + " / ".join(f"{x:.3f}" for x in rr) + " |")
    w()

    # ---- calibration ----
    w("## 2. Calibration (leave-one-system-out)")
    w()
    w("Correction fit on the log-ratio `L = log(true/est)`; the calibrated "
      "estimate is `est * exp(prediction)`. Skill is the RMS of `L` before "
      "calibration vs the RMS of the held-out residual after. `L` RMS of the "
      "raw estimate is the baseline (a perfect estimator has L=0).")
    w()
    raw_rms = rms([p["logr"] for p in pts])
    g_resid = loso_global(pts)
    lin_gap_frac_resid, lin_coefs = loso_linear(pts, ["gap", "frac"])
    lin_frac_resid, _ = loso_linear(pts, ["frac"])
    beta_full, r2_full = fit_insample_linear(pts, ["gap", "frac"])

    w("| model | params | in-sample | LOSO held-out RMS(L) | vs raw |")
    w("|---|---|---|---|---|")
    w(f"| raw estimate (no calib) | 0 | {raw_rms:.4f} | {raw_rms:.4f} | 1.00x |")
    w(f"| (a) global scale | 1 | -- | {rms(g_resid):.4f} | "
      f"{rms(g_resid)/raw_rms:.2f}x |")
    w(f"| (c) linear [frac] | 2 | -- | {rms(lin_frac_resid):.4f} | "
      f"{rms(lin_frac_resid)/raw_rms:.2f}x |")
    w(f"| (c) linear [gap, frac] | 3 | -- | {rms(lin_gap_frac_resid):.4f} | "
      f"{rms(lin_gap_frac_resid)/raw_rms:.2f}x |")
    w()
    w(f"Global scale factor (in-sample geomean of true/est) = {gm:.3f} "
      f"(i.e. the raw estimate on average captures {1.0/gm*100:.0f}% ... "
      f"equivalently multiply est by {gm:.3f} to hit the truth on average).")
    w()
    w(f"In-sample linear [gap, frac] R^2 = {r2_full:.3f}, coefficients "
      f"[b0, b_gap, b_frac] = [{beta_full[0]:.3f}, {beta_full[1]:.4f}, "
      f"{beta_full[2]:.3f}].")
    w()
    w("(b) Per-element scale is untestable out-of-sample here: every system is a "
      "distinct element set, so leave-one-system-out removes that element's only "
      "data and per-element degenerates to the global mean for the held-out "
      "point. Reported as not supported by N=6 distinct systems, not as a "
      "negative result.")
    w()

    # ---- cross term ----
    w("## 3. (ecut, k-mesh) cross term on fcc Al")
    w()
    ct = data["cross_term_Al"]
    w("3x3 grid, fixed FFT grid, reference corner (factor 1.00, k=8). "
      "`joint = E(ecut_i,k_j) - E_ref`; marginals hold the other axis at its "
      "reference; `cross = joint - marg_ecut - marg_k`. All meV/atom (Al: 1 "
      "atom/cell).")
    w()
    w("| factor | k-mesh | joint | marg_ecut | marg_k | cross | "
      "cross / |marg_ecut+marg_k| |")
    w("|---|---|---|---|---|---|---|")
    max_cross_frac = 0.0
    for g in ct["grid"]:
        summ = g["marg_ecut_eV"] + g["marg_k_eV"]
        frac = abs(g["cross_eV"]) / abs(summ) if summ != 0 else float("nan")
        if not math.isnan(frac) and not (g["factor"] == 1.0 and g["kmesh"] == 8):
            max_cross_frac = max(max_cross_frac, frac)
        w(f"| {g['factor']:.2f} | {g['kmesh']} | {g['joint_eV']*1e3:.3f} | "
          f"{g['marg_ecut_eV']*1e3:.3f} | {g['marg_k_eV']*1e3:.3f} | "
          f"{g['cross_eV']*1e3:.3f} | {frac:.3f} |")
    w()
    crosses = [abs(g["cross_eV"]) for g in ct["grid"]
               if not (g["factor"] == 1.0 and g["kmesh"] == 8)]
    w(f"Largest |cross| = {max(crosses)*1e3:.3f} meV/atom; largest "
      f"cross/(sum of marginals) = {max_cross_frac*100:.1f}%. This is the size "
      f"of the coupling the additive per-axis budget omits.")
    w()

    # write
    README.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\n[wrote {README}]")


if __name__ == "__main__":
    main()
